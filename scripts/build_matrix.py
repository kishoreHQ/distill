#!/usr/bin/env python3
"""Build the profile x domain matrix from imported front matter and config/domains.yaml."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from distilllib import (
    ROOT,
    contains_any,
    dump_json,
    field_blob,
    load_registry,
    load_yaml,
    profile_dirs,
    read_profile,
)


def classify_one(meta: dict, rules: dict) -> dict:
    mapping = rules["research_domain_map"]
    primary_research = meta["primary_domain"]
    mapped = mapping[primary_research]
    via = f"research:{primary_research}"
    secondary = []

    override = (rules.get("primary_overrides") or {}).get(meta["id"])
    keyword_hit = False
    if meta["primary_domain"] == "automation":
        spec = rules["automation_primary_keywords"]
        blob = field_blob(meta, spec["fields"])
        keyword_hit = contains_any(blob, spec["any"])

    if override:
        primary = override["domain"]
        via = "override"
        note = override["because"]
    elif keyword_hit:
        primary = rules["automation_primary_keywords"]["then_primary"]
        via = "keyword:automation-primary"
        note = "Research primary tag is automation and the front matter matches a DevOps/education keyword."
    else:
        primary = mapped
        note = ""

    if primary != mapped:
        secondary.append({"domain": mapped, "via": f"research-primary-demoted:{primary_research}"})

    for tag in meta.get("secondary_domains") or []:
        if tag not in mapping:
            secondary.append({"domain": tag, "via": "unmapped-research-tag"})
            continue
        domain = mapping[tag]
        if domain != primary:
            secondary.append({"domain": domain, "via": f"research:{tag}"})

    if meta.get("account_type") != "aggregator":
        for rule in rules.get("keyword_secondaries") or []:
            if meta.get("account_type") not in rule["account_types"]:
                continue
            blob = field_blob(meta, rule["fields"])
            if contains_any(blob, rule["any"]) and rule["domain"] != primary:
                secondary.append({"domain": rule["domain"], "via": rule["via"]})

    for extra in (rules.get("extra_secondaries") or {}).get(meta["id"], []):
        if extra["domain"] != primary:
            secondary.append(
                {
                    "domain": extra["domain"],
                    "via": "extra",
                    "because": extra["because"],
                }
            )

    deduped = []
    seen = set()
    for item in secondary:
        if item["domain"] in seen or item["domain"] == primary:
            continue
        seen.add(item["domain"])
        deduped.append(item)

    return {
        "id": meta["id"],
        "display_name": meta["display_name"],
        "account_type": meta["account_type"],
        "registry_status": "active",
        "research_primary": primary_research,
        "primary": primary,
        "primary_via": via,
        "note": note,
        "secondary": deduped,
        "board_eligibility": list(meta.get("board_eligibility") or []),
        "aggregator": meta.get("account_type") == "aggregator",
    }


def render_markdown(payload: dict) -> str:
    domains = payload["domains"]
    lines = [
        "# Classification matrix",
        "",
        "Generated by `scripts/build_matrix.py` from `profiles/*/profile.md` and `config/domains.yaml`.",
        "Do not edit by hand. Re-run the script after an import.",
        "",
        f"Snapshot date: {payload['snapshot_date']}. Active profiles: {payload['active_count']}.",
        "Excluded profiles are listed after the table and are not given a domain cell.",
        "",
        "Cell key: **P** primary, **S** secondary. The notes column says which rule fired.",
        "Research tags such as `automation` and `content-creation` are mapped in `config/domains.yaml`.",
        "",
        "| profile | account | " + " | ".join(item["title"] for item in domains) + " | via |",
        "|---|---|" + "|".join(["---"] * len(domains)) + "|---|",
    ]
    ids = [item["id"] for item in domains]
    for row in payload["profiles"]:
        cells = []
        secondary = {item["domain"]: item["via"] for item in row["secondary"]}
        for domain_id in ids:
            if row["primary"] == domain_id:
                cells.append("P")
            elif domain_id in secondary:
                cells.append("S")
            else:
                cells.append("")
        via_bits = [row["primary_via"]]
        via_bits.extend(f"{item['domain']} ({item['via']})" for item in row["secondary"])
        if row["aggregator"]:
            via_bits.append("signal feed, not a board member")
        lines.append(
            "| "
            + " | ".join(
                [row["id"], row["account_type"], *cells, "; ".join(via_bits)]
            )
            + " |"
        )
    lines.extend(
        [
            "",
            "## Excluded",
            "",
        ]
    )
    if not payload["excluded"]:
        lines.append("None.")
    for row in payload["excluded"]:
        reason = row.get("exclusion_reason") or "excluded"
        replaced = row.get("replaced_by")
        extra = f" Replaced by `{replaced}`." if replaced else ""
        lines.append(f"- `{row['id']}` ({row['display_name']}): {reason}.{extra}")
    lines.extend(
        [
            "",
            "## How to read a secondary",
            "",
            "- `research:<tag>` means the bundle's own secondary_domains list contained that tag.",
            "- `keyword:*` means a substring rule in config/domains.yaml matched front matter that was already imported.",
            "- `override` and `extra` are named in config/domains.yaml with a because-line.",
            "- An aggregator row is a feed. It is not a person and it is not on a board.",
            "",
        ]
    )
    return "\n".join(lines)


def build(root: Path) -> dict:
    rules = load_yaml(root / "config" / "domains.yaml")
    registry = load_registry(root)
    by_id = {row["id"]: row for row in registry["profiles"]}
    classified = []
    excluded = []
    for folder in profile_dirs(root):
        meta, _body = read_profile(folder)
        entry = by_id[meta["id"]]
        if entry["registry_status"] == "excluded":
            excluded.append(entry)
            continue
        classified.append(classify_one(meta, rules))
    classified.sort(key=lambda row: row["id"])
    payload = {
        "snapshot_date": registry["snapshot_date"],
        "active_count": len(classified),
        "domains": [{"id": item["id"], "title": item["title"]} for item in rules["domains"]],
        "profiles": classified,
        "excluded": [
            {
                "id": row["id"],
                "display_name": row["display_name"],
                "exclusion_reason": row.get("exclusion_reason"),
                "replaced_by": row.get("replaced_by"),
            }
            for row in excluded
        ],
    }
    return payload


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    payload = build(args.root)
    knowledge = args.root / "knowledge"
    knowledge.mkdir(parents=True, exist_ok=True)
    dump_json(payload, knowledge / "classification-matrix.json")
    (knowledge / "classification-matrix.md").write_text(render_markdown(payload) + "\n", encoding="utf-8")
    print(f"matrix active={payload['active_count']} excluded={len(payload['excluded'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
